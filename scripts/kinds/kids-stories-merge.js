// Kids stories of the culture, religion and movement profiles: scripts/kinds/kids-stories/<slug>.json (written with KIDS-STORIES-GUIDE.md from
// the packs of kids-packs.js, read by the editor) -> scripts/kids-stories.js (KIDS_STORIES {profile name: {title,
// pages: [{img, alt, credit, text}]}}), which generator.html renders (kidTaleHtml); regenerate the profiles after.
// A page's picture is a section key (empire-section-images.js), "home" (scripts/home-pictures.tsv) or an entry slug.
//   node scripts/kinds/kids-stories-merge.js [--check]
const fs = require('fs'), path = require('path'), vm = require('vm'), R = path.join(__dirname, '..', '..'), D = path.join(__dirname, 'kids-stories');
const b = {};
for (const f of ['shared-data.js', 'empire-section-images.js', 'encyclopedia-data.js'])
  vm.runInNewContext(fs.readFileSync(path.join(R, f), 'utf8') + '\n;for (const k of ["EMPIRES","SECTION_IMAGES","ENCYCLOPEDIA"]) { try { this[k] = eval(k); } catch (e) {} }', b);
const ENT = new Map(b.ENCYCLOPEDIA.filter(Boolean).map(e => [e.slug, e]));
const home = {};
for (const l of fs.readFileSync(path.join(R, 'scripts', 'home-pictures.tsv'), 'utf8').split(/\r?\n/)) { if (!l || l.startsWith('#')) continue; const [n, s] = l.split('\t'); if (s && s !== '-') home[n] = s; }
// the cultures (since 8 Nov 2026 also the religions and movements: their stories open their profiles too, but only the
// cultures' are listed in the Kids corner's "Stories of the peoples")
const KINDS = new Set(['culture', 'religion', 'movement']), cultures = new Set(b.EMPIRES.filter(e => KINDS.has(e.kind)).map(e => e.name)), peoples = new Set(b.EMPIRES.filter(e => e.kind === 'culture').map(e => e.name));
const credit = c => !c ? '' : typeof c === 'string' ? c : [c.artist, c.licence].filter(Boolean).join(', ');
const words = t => t.split(/\s+/).filter(Boolean).length;
// pictures not shown (no-pictures.txt, chosen by eye): such a page shows its words alone
const NOPIC = new Set(fs.readFileSync(path.join(D, 'no-pictures.txt'), 'utf8').split(/\r?\n/).map(l => l.trim()).filter(l => l && !l.startsWith('#')));
const out = {}, bad = []; let dropped = 0;
for (const f of fs.readdirSync(D).filter(f => f.endsWith('.json')).sort()) {
  const s = JSON.parse(fs.readFileSync(path.join(D, f), 'utf8')), where = f + ': ';
  if (!cultures.has(s.name)) { bad.push(where + 'no culture, religion or movement profile "' + s.name + '"'); continue; }
  const n = s.pages.reduce((a, p) => a + p.text.length, 0);
  if (s.pages.length < 4 || s.pages.length > 6) bad.push(where + s.pages.length + ' pages');
  if (n < 8 || n > 12) bad.push(where + n + ' sentences');
  const seen = new Set(), pages = [];
  for (const p of s.pages) {
    for (const t of p.text) if (words(t) > 22) bad.push(where + 'over 22 words: ' + t);
    if (p.pic !== '-' && seen.has(p.pic)) bad.push(where + 'picture twice: ' + p.pic); seen.add(p.pic);   // several pages may have none
    let pic = null, ps = null;
    const sec = (b.SECTION_IMAGES[s.name] || {})[p.pic];
    if (sec) { pic = { img: sec.img, alt: sec.name, credit: credit(sec) }; ps = sec.slug; }
    else { ps = p.pic === 'home' ? home[s.name] : p.pic; const e = ENT.get(ps); if (e && e.img) pic = { img: e.img, alt: e.name, credit: credit(e.credit) }; }
    if (!pic && p.pic !== '-') { bad.push(where + 'no picture for ' + p.pic); continue; }
    if (p.pic === '-' || NOPIC.has(ps)) { pic = null; dropped++; }
    pages.push(pic ? { img: pic.img, alt: pic.alt, credit: pic.credit, text: p.text } : { text: p.text });
  }
  out[s.name] = { title: s.title, pages };
}
if (bad.length) { console.error(bad.join('\n')); process.exit(1); }
const js = '// Generated by scripts/kinds/kids-stories-merge.js from scripts/kinds/kids-stories/*.json. Do not edit.\n// The Kids stories of the culture, religion and movement profiles, read by generator.html (kidTaleHtml).\nvar KIDS_STORIES = ' + JSON.stringify(out, null, 1) + ';\n';
// the Kids corner's "Stories of the peoples" (build:kids-tales in /kids): every story, oldest culture first, with its first
// picture as a thumbnail where one exists
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const start = Object.fromEntries(b.EMPIRES.filter(e => e.kind === 'culture').map(e => [e.name, e.start]));
const slugOf = {}; for (const f of fs.readdirSync(D).filter(f => f.endsWith('.json'))) slugOf[JSON.parse(fs.readFileSync(path.join(D, f), 'utf8')).name] = f.replace(/\.json$/, '');
const tales = Object.keys(out).filter(n => peoples.has(n)).sort((x, y) => start[x] - start[y] || x.localeCompare(y)).map(n => {
  const p = out[n].pages.find(p => p.img), th = p && p.img.replace('/images/encyclopedia/', '/images/encyclopedia/thumbs/');
  const img = th && fs.existsSync(path.join(R, th)) ? th : p && p.img;
  return '<li><a href="/culture/' + slugOf[n] + '">' + (img ? '<img src="' + esc(img) + '" alt="" loading="lazy" width="56" height="56">' : '<span class="kc-tale-ph" aria-hidden="true"></span>') + '<span>' + esc(out[n].title) + '</span></a></li>';
}).join('\n');
const KF = path.join(R, 'kids'); let kp = fs.readFileSync(KF, 'utf8');
const a = kp.indexOf('<!-- build:kids-tales -->'), z = kp.indexOf('<!-- /build:kids-tales -->');
if (a < 0 || z < 0) throw new Error('/kids has no build:kids-tales block');
kp = kp.slice(0, a) + '<!-- build:kids-tales -->\n' + tales + '\n' + kp.slice(z);
if (!process.argv.includes('--check')) { fs.writeFileSync(path.join(R, 'scripts', 'kids-stories.js'), js); fs.writeFileSync(KF, kp); }
console.log(dropped + ' pages without a picture; ' + Object.keys(out).length + ' stories' +(process.argv.includes('--check') ? ' (checked)' : ' written'));
